/**
 * WooCommerce module: sanitize (save) + read (submission) + issue a coupon.
 * Shape: settings.woocommerce = { coupon: bool, amount: string (percent, 0-100), days: string (valid for, empty = no expiry) }
 * One single-use percentage coupon is created per new subscriber; it is locked to the subscriber's email address
 * and returned in the submit response so the page can show it and add it to the cart.
 */
class WpPopPop_Woocommerce {

    const MODULE_KEY = 'acc-woocommerce';
    const MAX_DAYS   = 3650;

    public static function defaults() {
        return array('coupon' => false, 'amount' => '', 'days' => '');
    }

    private static function truthy($v) {
        return in_array($v, array(true, 1, '1', 'true', 'on'), true);
    }

    /** Clean, allow-listed config from a saved or posted value (object or array). */
    public static function sanitize($raw) {
        if (is_object($raw)) {
            $raw = get_object_vars($raw);
        }
        if (!is_array($raw)) {
            $raw = array();
        }
        $amount = '';
        if (isset($raw['amount']) && is_scalar($raw['amount'])) {
            $a = str_replace(',', '.', trim((string) $raw['amount']));
            if (preg_match('/^\d{1,3}(\.\d{1,2})?$/', $a) && (float) $a > 0 && (float) $a <= 100) {
                $amount = rtrim(rtrim(number_format((float) $a, 2, '.', ''), '0'), '.');
            }
        }
        $days = '';
        if (isset($raw['days']) && is_scalar($raw['days']) && preg_match('/^\d{1,4}$/', trim((string) $raw['days']))) {
            $d = (int) trim((string) $raw['days']);
            if ($d >= 1 && $d <= self::MAX_DAYS) {
                $days = (string) $d;
            }
        }
        return array(
            'coupon' => !empty($raw['coupon']) && self::truthy($raw['coupon']),
            'amount' => $amount,
            'days'   => $days,
        );
    }

    /** Config of a decoded popup: settings.woocommerce first, then a top-level woocommerce key. */
    public static function get_config($config) {
        $config = is_array($config) ? $config : array();
        $src    = array();
        if (isset($config['settings']['woocommerce']) && is_array($config['settings']['woocommerce'])) {
            $src = $config['settings']['woocommerce'];
        } elseif (isset($config['woocommerce']) && is_array($config['woocommerce'])) {
            $src = $config['woocommerce'];
        }
        return self::sanitize($src);
    }

    /** Settings > Module switch. A module that is switched off or deleted never affects the front end. */
    public static function module_active() {
        if (!class_exists('WpPopPop_Modules')) {
            return true;
        }
        /* Not registered: the bundled package is seeded on the first admin load, so stay on until then. A deleted module is off. */
        if (!WpPopPop_Modules::get(self::MODULE_KEY)) {
            $orphans = WpPopPop_Modules::orphans();
            return !isset($orphans[self::MODULE_KEY]);
        }
        if (!class_exists('WpPopPop_Admin_Settings')) {
            require_once WPPOPPOP_PATH . 'includes/admin/class-admin-settings.php';
        }
        return WpPopPop_Admin_Settings::module_enabled(self::MODULE_KEY);
    }

    /** Create one WooCommerce coupon. Returns the code, or false when WooCommerce is missing or the save fails. */
    public static function generate(array $args) {
        if (!class_exists('WC_Coupon')) {
            return false;
        }
        $prefix = !empty($args['prefix']) ? sanitize_key($args['prefix']) : 'POP';
        $type   = !empty($args['type']) ? sanitize_key($args['type']) : 'percent'; // percent, fixed_cart, fixed_product
        $amount = isset($args['amount']) ? (float) $args['amount'] : 10.0;
        $code   = strtoupper($prefix . '_' . wp_generate_password(8, false));
        try {
            $coupon = new WC_Coupon();
            $coupon->set_code($code);
            $coupon->set_discount_type($type);
            $coupon->set_amount($amount);
            $coupon->set_individual_use(true);
            $coupon->set_usage_limit(1);
            $coupon->set_description(__('Generated by WpPopPop campaign', 'wppoppop'));
            if (!empty($args['email']) && is_email($args['email'])) {
                $coupon->set_email_restrictions(array(sanitize_email($args['email'])));
            }
            if (!empty($args['expiry_days'])) {
                $expiry = (new DateTime())->modify('+' . (int) $args['expiry_days'] . ' days');
                $coupon->set_date_expires($expiry->getTimestamp());
            }
            $coupon->save();
        } catch (Exception $e) {
            return false;
        }
        if (function_exists('wppoppop_log_event')) {
            wppoppop_log_event('wc_coupon_created', 'Created coupon: ' . $code, array('amount' => $amount, 'type' => $type));
        }
        return $code;
    }

    /** Coupon code for a new subscriber ('' when nothing is issued). The same email gets the same code again for this popup. */
    public static function issue($uid, $email, $cfg) {
        if (!is_array($cfg) || empty($cfg['coupon']) || (float) $cfg['amount'] <= 0 || !class_exists('WC_Coupon') || !self::module_active()) {
            return '';
        }
        $email = is_string($email) ? $email : '';
        $key   = ($email !== '' && is_email($email)) ? 'wppoppop_wc_' . md5((string) $uid . '|' . strtolower($email)) : '';
        if ($key !== '') {
            $prev = get_transient($key);
            if (is_string($prev) && $prev !== '') {
                return $prev;
            }
        }
        $code = self::generate(array(
            'type'        => 'percent',
            'amount'      => $cfg['amount'],
            'expiry_days' => $cfg['days'],
            'email'       => $key !== '' ? $email : '',
        ));
        if (!is_string($code) || $code === '') {
            return '';
        }
        if ($key !== '') {
            $days = $cfg['days'] !== '' ? (int) $cfg['days'] : 365;
            set_transient($key, $code, $days * DAY_IN_SECONDS);
        }
        return $code;
    }
}
